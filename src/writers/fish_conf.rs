use crate::{Theme, ThemeError, Writer, fish_conf_file};
use std::path::PathBuf;

pub struct FishConf;

impl Writer for FishConf {
    fn name(&self) -> &'static str { "fish" }

    fn output_path(&self) -> PathBuf { fish_conf_file() }

    fn generate(&self, theme: &Theme) -> Result<String, ThemeError> {
        let mut out = String::from("# Generated by theme-manager. Do not edit manually.\n");
        out.push_str(&format!("set -gx THEME_NAME '{}'\n", theme.name));
        out.push_str(&format!("set -gx THEME_PATH '{}'\n", theme.path.display()));

        for (key, val) in &theme.vars {
            // Single-quote the value so # in hex colors is not a fish comment.
            // Escape any literal single quotes in the value (rare but defensive).
            let escaped = val.replace('\'', "'\\''");
            out.push_str(&format!("set -gx THEME_{key} '{escaped}'\n"));
        }

        Ok(out)
    }
}
