use crate::{Theme, ThemeError, Writer};
use std::path::PathBuf;
use std::process::Command;

pub struct GtkSettings;
pub struct Qt6ct;

// ---------------------------------------------------------------------------
// GTK settings.ini — written for both gtk-3.0 and gtk-4.0
// ---------------------------------------------------------------------------

// ---------------------------------------------------------------------------
// GTK theme snippets — one per GTK major version.
//
// These writers NEVER touch your real settings.ini. GTK offers no include
// mechanism, so each one writes a small manager-owned snippet next to it
// whose header tells you which lines to merge once. The live variant is
// also applied via gsettings on every theme switch (see
// apply_system_variant), so file-based merging is only needed on systems
// without a settings portal.
// ---------------------------------------------------------------------------

impl Writer for GtkSettings {
    fn name(&self) -> &'static str {
        "gtk"
    }

    fn output_path(&self) -> PathBuf {
        crate::home().join(".config/gtk-3.0/theme-manager.ini")
    }

    fn generate(&self, theme: &Theme) -> Result<String, ThemeError> {
        gtk_settings_content(theme, ".config/gtk-3.0/settings.ini")
    }

    fn reload(&self) {}
}

pub struct Gtk4Settings;

impl Writer for Gtk4Settings {
    fn name(&self) -> &'static str {
        "gtk4"
    }

    fn output_path(&self) -> PathBuf {
        crate::home().join(".config/gtk-4.0/theme-manager.ini")
    }

    fn generate(&self, theme: &Theme) -> Result<String, ThemeError> {
        gtk_settings_content(theme, ".config/gtk-4.0/settings.ini")
    }

    // gsettings covers both gtk3 and gtk4 so no second call needed here.
    fn reload(&self) {}
}

fn gtk_settings_content(theme: &Theme, settings_rel: &str) -> Result<String, ThemeError> {
    let prefer_dark = match theme.require("VARIANT")? {
        "dark" => "1",
        "light" => "0",
        v => return Err(ThemeError::InvalidVariant(v.to_string())),
    };

    Ok(format!(
        "# Generated by theme-manager. Do not edit manually.\n\
         # To use: GTK has no include mechanism, so copy the [Settings]\n\
         # section below into ~/{settings_rel} yourself (one-time setup).\n\
         # The live variant is also applied via gsettings on every switch.\n\
         #\n\
         [Settings]\n\
         gtk-application-prefer-dark-theme = {prefer_dark}\n"
    ))
}

pub fn apply_system_variant(theme: &Theme) {
    let variant = match theme.vars.get("VARIANT").map(String::as_str) {
        Some("dark") => "dark",
        Some("light") => "light",
        Some(variant) => {
            eprintln!("theme-manager: [variant] invalid variant '{variant}'");
            return;
        }
        None => {
            eprintln!("theme-manager: [variant] VARIANT is missing");
            return;
        }
    };
    let (color_scheme, gtk_theme) = if variant == "dark" {
        ("prefer-dark", "ThemeManager")
    } else {
        ("prefer-light", "ThemeManager")
    };

    set_gsetting("org.gnome.desktop.interface", "color-scheme", color_scheme);
    set_gsetting("org.gnome.desktop.interface", "gtk-theme", gtk_theme);
    update_activation_environment(variant, gtk_theme);
}

fn set_gsetting(schema: &str, key: &str, value: &str) {
    let result = Command::new("gsettings")
        .args(["set", schema, key, value])
        .status();

    match result {
        Ok(status) if status.success() => {
            eprintln!("theme-manager: [variant] gsettings {key} → {value}");
        }
        Ok(status) => eprintln!("theme-manager: [variant] gsettings {key} exited with {status}"),
        Err(e) => eprintln!("theme-manager: [variant] gsettings not found: {e}"),
    }
}

fn update_activation_environment(variant: &str, gtk_theme: &str) {
    let assignments = [
        format!("THEME_VARIANT={variant}"),
        format!("GTK_THEME={gtk_theme}"),
        "QT_QPA_PLATFORMTHEME=qt6ct".to_string(),
    ];
    let assignment_refs: Vec<&str> = assignments.iter().map(String::as_str).collect();

    run_environment_command(
        "dbus-update-activation-environment",
        &["--systemd"],
        &assignment_refs,
    );
}

fn run_environment_command(command: &str, args: &[&str], values: &[&str]) {
    let result = Command::new(command).args(args).args(values).status();
    match result {
        Ok(status) if status.success() => {}
        Ok(status) => eprintln!("theme-manager: [variant] {command} exited with {status}"),
        Err(e) => eprintln!("theme-manager: [variant] {command} not found: {e}"),
    }
}

// ---------------------------------------------------------------------------
// Qt6ct
// ---------------------------------------------------------------------------

impl Writer for Qt6ct {
    fn name(&self) -> &'static str {
        "qt6ct"
    }

    // Manager-owned snippet, never your real qt6ct.conf. Qt6ct has no
    // include mechanism, so the header tells you which lines to copy once.
    fn output_path(&self) -> PathBuf {
        crate::home().join(".config/qt6ct/theme-manager.conf")
    }

    fn generate(&self, theme: &Theme) -> Result<String, ThemeError> {
        let color_scheme = match theme.require("VARIANT")? {
            "dark" | "light" => "theme-manager.conf",
            v => return Err(ThemeError::InvalidVariant(v.to_string())),
        };

        Ok(format!(
            "# Generated by theme-manager. Do not edit manually.\n\
             # To use: qt6ct has no include mechanism. Copy these lines into\n\
             # [Appearance] of ~/.config/qt6ct/qt6ct.conf (one-time setup).\n\
             # Install Darkly's Qt6 style plugin separately; restart Qt apps.\n\
             [Appearance]\n\
             color_scheme_path={}/.config/qt6ct/colors/{color_scheme}\n\
             style=darkly\n",
            crate::home().display()
        ))
    }
}
