use crate::{Theme, ThemeError, Writer};
use std::path::PathBuf;
use std::process::Command;

pub struct Vicinae {
    pub name: String,
}

impl Writer for Vicinae {
    fn name(&self) -> &'static str {
        "vicinae"
    }

    fn output_path(&self) -> PathBuf {
        crate::home().join(format!(".config/vicinae/themes/{}.toml", self.name))
    }

    fn enabled(&self) -> bool {
        crate::app_enabled("vicinae", ".config/vicinae")
    }

    fn generate(&self, theme: &Theme) -> Result<String, ThemeError> {
        let t = theme;
        let name = &self.name;
        // Vicinae accepts #AARRGGBB; retain fully colored controls and text.
        let surface = |key| -> Result<String, ThemeError> {
            let color = t.require(key)?;
            Ok( color.to_string())
        };
        Ok(format!(
            "# Generated by theme-manager. Do not edit manually.\n\
             # To use: vicinae theme set {name}\n\
             # (theme-set applies it automatically after writing this file.)\n\
             #\n\
             [meta]\n\
             name        = \"{name}\"\n\
             description = \"Generated by theme-manager\"\n\
             variant     = \"dark\"\n\
             inherits    = \"vicinae-dark\"\n\
             \n\
             [colors.core]\n\
             accent               = \"{}\"\n\
             accent_foreground    = \"{}\"\n\
             background           = \"{}\"\n\
             foreground           = \"{}\"\n\
             secondary_background = \"{}\"\n\
             border               = \"colors.core.background\"\n\
             \n\
             [colors.main_window]\n\
             border = \"colors.core.background\"\n\
             footer = {{ background = \"colors.core.secondary_background\" }}\n\
             \n\
             [colors.settings_window]\n\
             border = \"colors.core.border\"\n\
             \n\
             [colors.accents]\n\
             blue    = \"{}\"\n\
             green   = \"{}\"\n\
             magenta = \"{}\"\n\
             orange  = \"{}\"\n\
             red     = \"{}\"\n\
             yellow  = \"{}\"\n\
             cyan    = \"{}\"\n\
             purple  = \"{}\"\n\
             \n\
             [colors.shortcut]\n\
             border = \"colors.core.border\"\n\
             \n\
             [colors.text]\n\
             default     = \"{}\"\n\
             muted       = \"{}\"\n\
             danger      = \"{}\"\n\
             success     = \"{}\"\n\
             placeholder = \"{}\"\n\
             selection   = {{ background = \"{}\", foreground = \"{}\" }}\n\
             \n\
             [colors.text.links]\n\
             default = \"{}\"\n\
             visited = \"{}\"\n\
             \n\
             [colors.input]\n\
             border       = \"{}\"\n\
             border_focus = \"{}\"\n\
             border_error = \"{}\"\n\
             \n\
             [colors.button.primary]\n\
             background = \"{}\"\n\
             foreground = \"{}\"\n\
             hover      = {{ background = \"{}\" }}\n\
             focus      = {{ outline = \"colors.core.accent\" }}\n\
             \n\
             [colors.list.item.hover]\n\
             foreground           = \"{}\"\n\
             secondary_foreground = \"{}\"\n\
             \n\
             [colors.list.item.selection]\n\
             background           = \"{}\"\n\
             foreground           = \"{}\"\n\
             secondary_background = \"{}\"\n\
             secondary_foreground = \"{}\"\n\
             \n\
             [colors.grid.item]\n\
             background = \"{}\"\n\
             hover      = {{ outline = \"{}\" }}\n\
             selection  = {{ outline = \"{}\" }}\n\
             \n\
             [colors.scrollbars]\n\
             background = \"{}\"\n\
             \n\
             [colors.loading]\n\
             bar     = \"{}\"\n\
             spinner = \"{}\"\n",
            t.require("RED")?,          // accent
            t.require("DARKER_BLACK")?, // accent_foreground
            surface("BLACK")?,          // background
            t.require("WHITE")?,        // foreground
            surface("BLACK")?,          // secondary_background
            // accents
            t.require("TEAL")?,
            t.require("GREEN")?,
            t.require("BABY_PINK")?,
            t.require("PINK")?,
            t.require("RED")?,
            t.require("YELLOW")?,
            t.require("TEAL")?,
            t.require("PURPLE")?,
            // text
            t.require("WHITE")?,
            t.require("BASE03")?,
            t.require("RED")?,
            t.require("GREEN")?,
            t.require("BASE03")?,
            t.require("GREY")?,
            t.require("WHITE")?,
            // links
            t.require("TEAL")?,
            t.require("BLUE")?,
            // input
            t.require("BLACK")?,
            t.require("TEAL")?,
            t.require("RED")?,
            // button.primary
            t.require("DARKER_BLACK")?,
            t.require("WHITE")?,
            t.require("DARKER_BLACK")?,
            // list.item.hover
            t.require("WHITE")?,
            t.require("BASE03")?,
            // list.item.selection
            t.require("BASE01")?,
            t.require("WHITE")?,
            t.require("BLACK")?,
            t.require("BASE03")?,
            // grid.item
            t.require("BLACK")?,
            t.require("WHITE")?,
            t.require("WHITE")?,
            // scrollbars
            t.require("BLACK")?,
            // loading
            t.require("TEAL")?,
            t.require("TEAL")?,
        ))
    }

    fn reload(&self) {
        let name = &self.name;
        let status = Command::new("vicinae")
            .args(["theme", "set", name])
            .status();
        match status {
            Ok(s) if s.success() => eprintln!("theme-manager: [vicinae] applied theme '{name}'"),
            Ok(s) => eprintln!("theme-manager: [vicinae] theme set exited with {s}"),
            Err(e) => eprintln!("theme-manager: [vicinae] not found or failed: {e}"),
        }
    }
}
