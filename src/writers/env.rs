//! Global (shell-agnostic) environment writers.
//!
//! The fish-only `theme_vars.fish` left every other shell and GUI app behind.
//! These three writers publish the same `THEME_*` set everywhere else:
//!
//! - `EnvSh` — POSIX `export` file for bash/zsh/sh (`source` it from rc files).
//! - `EnvSystemd` — `environment.d` snippet, loaded by the systemd user
//!   manager at login for GUI apps, portals, and user services.
//! - `HyprEnv` — `hl.env(...)` calls for Hyprland, so apps launched from the
//!   compositor inherit the palette.
//!
//! Live propagation (no relogin) is handled by [`apply_global_env`], which
//! pushes the same assignments into the running session via
//! `systemctl --user set-environment`, `dbus-update-activation-environment`,
//! and `hyprctl setenv`. All propagation is best-effort, matching
//! `variant::apply_system_variant`.
use crate::{Theme, ThemeError, Writer};
use std::path::PathBuf;
use std::process::Command;

/// Sorted `(NAME, value)` pairs published to every global target.
///
/// Mirrors `FishConf`: `THEME_NAME`, `THEME_PATH`, the two toolkit vars, plus
/// `THEME_<KEY>` for every resolved theme key. Sorted so output is stable
/// across switches and writers.
pub fn collect_env(theme: &Theme) -> Result<Vec<(String, String)>, ThemeError> {
    match theme.require("VARIANT")? {
        "dark" | "light" => {}
        variant => return Err(ThemeError::InvalidVariant(variant.to_string())),
    };
    let mut vars = vec![
        ("THEME_NAME".to_string(), theme.name.clone()),
        (
            "THEME_PATH".to_string(),
            theme.path.display().to_string(),
        ),
        ("GTK_THEME".to_string(), "ThemeManager".to_string()),
        ("QT_QPA_PLATFORMTHEME".to_string(), "qt6ct".to_string()),
    ];
    let mut themed: Vec<_> = theme
        .vars
        .iter()
        .map(|(key, val)| (format!("THEME_{key}"), val.clone()))
        .collect();
    themed.sort_by(|a, b| a.0.cmp(&b.0));
    vars.extend(themed);
    Ok(vars)
}

fn sh_escape(value: &str) -> String {
    // POSIX single-quote: wrap in '...' and splice each literal ' as '\''.
    value.replace('\'', "'\\''")
}

fn lua_escape(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            c => out.push(c),
        }
    }
    out
}

pub struct EnvSh;

impl Writer for EnvSh {
    fn name(&self) -> &'static str {
        "env-sh"
    }

    fn output_path(&self) -> PathBuf {
        crate::env_sh_file()
    }

    fn generate(&self, theme: &Theme) -> Result<String, ThemeError> {
        let mut out = String::from(
            "# Generated by theme-manager. Do not edit manually.\n\
             # To use: source this file from your shell rc files, e.g. in ~/.bashrc:\n\
             #   [ -f \"$HOME/.config/theme-manager/theme_env.sh\" ] && . \"$HOME/.config/theme-manager/theme_env.sh\"\n",
        );
        for (key, val) in collect_env(theme)? {
            out.push_str(&format!("export {key}='{}'\n", sh_escape(&val)));
        }
        Ok(out)
    }
}

pub struct EnvSystemd;

impl Writer for EnvSystemd {
    fn name(&self) -> &'static str {
        "env-systemd"
    }

    fn output_path(&self) -> PathBuf {
        crate::env_systemd_file()
    }

    fn generate(&self, theme: &Theme) -> Result<String, ThemeError> {
        let mut out = String::from(
            "# Generated by theme-manager. Do not edit manually.\n\
             # To use: nothing to import — the systemd user manager loads\n\
             # ~/.config/environment.d/*.conf at login, so GUI apps, portals,\n\
             # and user services inherit these vars. Updated live on every\n\
             # switch via systemctl/dbus (see apply_global_env).\n",
        );
        // environment.d has no shell quoting: `NAME=value` lines, literal `#`
        // after `=` is fine, but newlines would break the format, so strip them.
        for (key, val) in collect_env(theme)? {
            let flat = val.replace(['\n', '\r'], "");
            out.push_str(&format!("{key}={flat}\n"));
        }
        Ok(out)
    }
}

pub struct HyprEnv;

impl Writer for HyprEnv {
    fn name(&self) -> &'static str {
        "hypr-env"
    }

    fn output_path(&self) -> PathBuf {
        crate::hypr_env_file()
    }

    fn enabled(&self) -> bool {
        crate::app_enabled("hyprctl", ".config/hypr")
    }

    fn generate(&self, theme: &Theme) -> Result<String, ThemeError> {
        let mut out = String::from(
            "-- Generated by theme-manager -- do not edit manually.\n\
             -- To use: add this line to ~/.config/hypr/hyprland.lua (after require(\"colors\")):\n\
             --   require(\"theme_env\")\n\
             -- Apps launched from Hyprland then inherit every THEME_* var.\n",
        );
        for (key, val) in collect_env(theme)? {
            out.push_str(&format!("hl.env(\"{key}\", \"{}\")\n", lua_escape(&val)));
        }
        Ok(out)
    }
}

/// Push the resolved palette into the running session so newly launched apps
/// inherit it without a relogin. Best-effort: missing helpers (headless
/// test hosts, non-systemd sessions) only log.
pub fn apply_global_env(theme: &Theme) {
    let vars = match collect_env(theme) {
        Ok(vars) => vars,
        Err(e) => {
            eprintln!("theme-manager: [env] collect failed: {e}");
            return;
        }
    };
    let assignments: Vec<String> =
        vars.iter().map(|(k, v)| format!("{k}={v}")).collect();
    let refs: Vec<&str> = assignments.iter().map(String::as_str).collect();

    run_env_cmd(
        "systemctl",
        &["--user", "set-environment"],
        &refs,
        "systemctl --user set-environment",
    );
    run_env_cmd(
        "dbus-update-activation-environment",
        &["--systemd"],
        &refs,
        "dbus-update-activation-environment",
    );
    // hyprctl takes one variable per invocation.
    for (key, val) in &vars {
        let result = Command::new("hyprctl")
            .args(["setenv", key, val])
            .output();
        match result {
            Ok(o) if o.status.success() => {}
            Ok(o) => eprintln!(
                "theme-manager: [env] hyprctl setenv {key} exited with {}",
                o.status
            ),
            Err(e) => {
                eprintln!("theme-manager: [env] hyprctl not found: {e}");
                break;
            }
        }
    }
}

fn run_env_cmd(command: &str, args: &[&str], values: &[&str], label: &str) {
    match Command::new(command).args(args).args(values).status() {
        Ok(status) if status.success() => {
            eprintln!("theme-manager: [env] {label} updated");
        }
        Ok(status) => eprintln!("theme-manager: [env] {label} exited with {status}"),
        Err(e) => eprintln!("theme-manager: [env] {command} not found: {e}"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashMap;

    fn theme() -> Theme {
        Theme {
            name: "t".into(),
            path: "/tmp/t".into(),
            vars: HashMap::from([
                ("VARIANT".to_string(), "dark".to_string()),
                ("BASE00".to_string(), "#112233".to_string()),
                ("QUOTEY".to_string(), "a'b".to_string()),
            ]),
        }
    }

    #[test]
    fn env_set_is_sorted_and_mirrors_fish() {
        let vars = collect_env(&theme()).unwrap();
        let names: Vec<_> = vars.iter().map(|(k, _)| k.as_str()).collect();
        assert!(names.contains(&"THEME_NAME"));
        assert!(names.contains(&"THEME_PATH"));
        assert!(names.contains(&"GTK_THEME"));
        assert!(names.contains(&"QT_QPA_PLATFORMTHEME"));
        assert!(names.contains(&"THEME_VARIANT"));
        assert!(names.contains(&"THEME_BASE00"));
        let mut sorted = names.clone();
        sorted.sort_unstable();
        // THEME_NAME/PATH + toolkit vars come first, THEME_* tail is sorted.
        let tail: Vec<_> = names.iter().skip(4).collect();
        let mut tail_sorted = tail.clone();
        tail_sorted.sort_unstable();
        assert_eq!(tail, tail_sorted);
    }

    #[test]
    fn sh_escapes_single_quotes_posix_style() {
        let out = EnvSh.generate(&theme()).unwrap();
        assert!(out.contains("export THEME_QUOTEY='a'\\''b'"));
        assert!(out.contains("To use:"));
    }

    #[test]
    fn systemd_has_no_shell_syntax() {
        let out = EnvSystemd.generate(&theme()).unwrap();
        assert!(out.contains("THEME_BASE00=#112233"));
        assert!(out.contains("environment.d"));
        assert!(!out.contains("export "));
    }

    #[test]
    fn hypr_env_emits_hl_env_calls() {
        let out = HyprEnv.generate(&theme()).unwrap();
        assert!(out.contains("require(\"theme_env\")"));
        assert!(out.contains("hl.env(\"THEME_BASE00\", \"#112233\")"));
    }

    #[test]
    fn invalid_variant_fails_all_env_targets() {
        let mut t = theme();
        t.vars.insert("VARIANT".into(), "neon".into());
        assert!(EnvSh.generate(&t).is_err());
        assert!(EnvSystemd.generate(&t).is_err());
        assert!(HyprEnv.generate(&t).is_err());
    }
}
