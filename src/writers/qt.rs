//! Darkly-compatible Qt6/KDE palette outputs. Darkly itself is a compiled
//! QStyle plugin: these files recolor it, but do not bundle its binary.
use crate::{hex_to_rgb, Theme, ThemeError, Writer};
use std::path::PathBuf;

pub struct Qt6Colors;
pub struct KdeColors;

fn color(theme: &Theme, key: &str, fallback: &str) -> Result<String, ThemeError> {
    let value = theme.vars.get(key).map(String::as_str).unwrap_or(fallback);
    hex_to_rgb(value)?;
    Ok(value.to_ascii_lowercase())
}

fn rgb(hex: &str) -> String {
    let (r, g, b) = hex_to_rgb(hex).expect("validated palette");
    format!("{r},{g},{b}")
}

struct Palette {
    window: String,
    button: String,
    base: String,
    alternate: String,
    border: String,
    text: String,
    muted: String,
    highlight: String,
    highlighted_text: String,
    red: String,
    green: String,
    yellow: String,
    link: String,
    visited: String,
}

impl Palette {
    fn from_theme(t: &Theme) -> Result<Self, ThemeError> {
        let window = color(t, "BASE00", "#20212b")?;
        let button = color(t, "BASE01", &window)?;
        let base = color(t, "BASE02", &button)?;
        let alternate = color(t, "BASE03", &base)?;
        let border = color(t, "BORDER_COLOR", &alternate)?;
        let text = color(t, "BASE05", "#eeeeee")?;
        let muted = color(t, "BASE04", &text)?;
        let highlight = color(t, "BASE0D", "#3478da")?;
        let (r, g, b) = hex_to_rgb(&highlight)?;
        let highlighted_text = if (r as f64 * 0.299 + g as f64 * 0.587 + b as f64 * 0.114) > 150.0 {
            "#111318"
        } else {
            "#ffffff"
        }.to_string();
        Ok(Self {
            window, button, base, alternate, border, text, muted,
            red: color(t, "BASE08", "#da4453")?,
            green: color(t, "BASE0B", "#24ad59")?,
            yellow: color(t, "BASE09", "#f67400")?,
            link: highlight.clone(),
            visited: color(t, "BASE0E", &highlight)?,
            highlight, highlighted_text,
        })
    }

    // QPalette roles 0..21, in Qt enum order (including NoRole at index 17).
    fn qt_roles(&self, disabled: bool, inactive: bool) -> String {
        let text = if disabled || inactive { &self.muted } else { &self.text };
        let highlight = if disabled || inactive { &self.alternate } else { &self.highlight };
        let selection_text = if disabled || inactive { &self.text } else { &self.highlighted_text };
        let colors = [
            text, &self.button, &self.alternate, &self.base, &self.border,
            &self.alternate, text, &self.text, text, &self.base,
            &self.window, &self.border, highlight, selection_text, &self.link,
            &self.visited, &self.alternate, text, &self.base, text, &self.muted,
            highlight,
        ];
        colors.iter().map(|c| format!("#ff{}", &c[1..])).collect::<Vec<_>>().join(", ")
    }
}

impl Writer for Qt6Colors {
    fn name(&self) -> &'static str { "qt6-colors" }
    fn output_path(&self) -> PathBuf {
        crate::home().join(".config/qt6ct/colors/theme-manager.conf")
    }
    fn generate(&self, theme: &Theme) -> Result<String, ThemeError> {
        let p = Palette::from_theme(theme)?;
        Ok(format!(
            "# Generated by theme-manager. Do not edit manually.\n\
             # To use: set color_scheme_path={}/.config/qt6ct/colors/theme-manager.conf\n\
             # in [Appearance] of ~/.config/qt6ct/qt6ct.conf.\n\
             [ColorScheme]\nactive_colors={}\ndisabled_colors={}\ninactive_colors={}\n",
            crate::home().display(),
            p.qt_roles(false, false), p.qt_roles(true, false), p.qt_roles(false, true)
        ))
    }
}

impl Writer for KdeColors {
    fn name(&self) -> &'static str { "kde-colors" }
    fn output_path(&self) -> PathBuf {
        crate::home().join(".local/share/color-schemes/ThemeManager.colors")
    }
    fn generate(&self, theme: &Theme) -> Result<String, ThemeError> {
        let p = Palette::from_theme(theme)?;
        let mut out = format!(
            "# Generated by theme-manager from Darkly's KDE color scheme. Do not edit manually.\n\
             # To use: install Darkly Qt6 plugin separately, then select ThemeManager\n\
             # color scheme in KDE settings (or run plasma-apply-colorscheme ThemeManager).\n\
             [ColorEffects:Disabled]\nColor={}\nColorAmount=0.5\nColorEffect=3\nContrastAmount=0.5\nContrastEffect=0\nIntensityAmount=0\nIntensityEffect=0\n\n\
             [ColorEffects:Inactive]\nChangeSelectionColor=true\nColor={}\nColorAmount=0.4\nColorEffect=3\nContrastAmount=0.4\nContrastEffect=0\nEnable=true\nIntensityAmount=-0.2\nIntensityEffect=0\n\n",
            rgb(&p.base), rgb(&p.alternate)
        );
        for (group, bg, alt, fg, active) in [
            ("Button", &p.button, &p.base, &p.text, &p.highlight),
            ("Complementary", &p.base, &p.alternate, &p.text, &p.highlight),
            ("Selection", &p.highlight, &p.alternate, &p.highlighted_text, &p.highlighted_text),
            ("Tooltip", &p.base, &p.alternate, &p.text, &p.highlight),
            ("View", &p.base, &p.button, &p.text, &p.highlight),
            ("Window", &p.window, &p.button, &p.text, &p.highlight),
        ] {
            out.push_str(&format!(
                "[Colors:{group}]\nBackgroundAlternate={}\nBackgroundNormal={}\n\
                 DecorationFocus={}\nDecorationHover={}\nForegroundActive={}\n\
                 ForegroundInactive={}\nForegroundLink={}\nForegroundNegative={}\n\
                 ForegroundNeutral={}\nForegroundNormal={}\nForegroundPositive={}\n\
                 ForegroundVisited={}\n\n",
                rgb(alt), rgb(bg), rgb(&p.highlight), rgb(&p.highlight), rgb(active),
                rgb(&p.muted), rgb(&p.link), rgb(&p.red), rgb(&p.yellow),
                rgb(fg), rgb(&p.green), rgb(&p.visited)
            ));
        }
        out.push_str(&format!(
            "[General]\nColorScheme=ThemeManager\nName=ThemeManager\nshadeSortColumn=true\n\n\
             [KDE]\ncontrast=0\n\n[WM]\nactiveBackground={}\nactiveBlend={}\n\
             activeForeground={}\ninactiveBackground={}\ninactiveBlend={}\n\
             inactiveForeground={}\n",
            rgb(&p.window), rgb(&p.text), rgb(&p.text), rgb(&p.base),
            rgb(&p.base), rgb(&p.muted)
        ));
        Ok(out)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashMap;
    #[test]
    fn palettes_match_qt_roles_and_darkly_kde_groups() {
        let mut t = Theme { name: "test".into(), path: "/tmp/test".into(), vars: HashMap::from([
            ("BASE00".into(), "#101020".into()),
            ("BASE05".into(), "#eeeeee".into()),
            ("BASE0D".into(), "#dddddd".into()),
        ]) };
        let qt = Qt6Colors.generate(&t).unwrap();
        let snippet = crate::writers::Qt6ct.generate(&Theme {
            vars: HashMap::from([("VARIANT".into(), "light".into())]),
            ..t.clone()
        }).unwrap();
        assert!(snippet.contains(&format!("color_scheme_path={}", Qt6Colors.output_path().display())));
        assert!(snippet.contains("style=darkly"));
        for key in ["active_colors", "disabled_colors", "inactive_colors"] {
            let roles = qt.lines().find(|l| l.starts_with(key)).unwrap().split_once('=').unwrap().1;
            let roles: Vec<_> = roles.split(", ").collect();
            assert_eq!(roles.len(), 22);
            assert_eq!(roles[10], "#ff101020"); // Window
            assert_eq!(roles[12], if key == "active_colors" { "#ffdddddd" } else { "#ff101020" }); // Highlight
            assert_eq!(roles[13], if key == "active_colors" { "#ff111318" } else { "#ffeeeeee" }); // HighlightedText
        }
        let kde = KdeColors.generate(&t).unwrap();
        for group in ["Button", "Complementary", "Selection", "Tooltip", "View", "Window"] {
            assert!(kde.contains(&format!("[Colors:{group}]")));
        }
        assert!(kde.contains("BackgroundNormal=16,16,32"));
        assert!(kde.contains("ForegroundNormal=17,19,24"));
        t.vars.insert("BASE0D".into(), "#223355".into());
        assert!(KdeColors.generate(&t).unwrap().contains("ForegroundNormal=255,255,255"));
        t.vars.insert("BASE00".into(), "invalid".into());
        assert!(Qt6Colors.generate(&t).is_err());
    }
}
