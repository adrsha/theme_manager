use crate::{hex_to_rgb, Theme, ThemeError, Writer};
use std::path::PathBuf;

type Rgb = (u8, u8, u8);

pub struct FirefoxCss;

impl Writer for FirefoxCss {
    fn name(&self) -> &'static str {
        "firefox-css"
    }
    fn output_path(&self) -> PathBuf {
        crate::home().join(".config/theme-manager/firefox-colors.css")
    }
    fn enabled(&self) -> bool {
        crate::app_enabled("firefox", ".mozilla/firefox")
            || crate::home().join(".config/mozilla/firefox").is_dir()
    }
    fn generate(&self, theme: &Theme) -> Result<String, ThemeError> {
        colors(theme)
    }
    // Firefox only re-reads chrome CSS on restart.
    fn reload(&self) {}
}

fn palette_uri() -> String {
    let path = crate::home().join(".config/theme-manager/firefox-colors.css");
    let mut uri = String::from("file://");
    for byte in path.to_string_lossy().bytes() {
        if byte.is_ascii_alphanumeric() || b"/-._~".contains(&byte) {
            uri.push(byte as char);
        } else {
            uri.push_str(&format!("%{byte:02X}"));
        }
    }
    uri
}

fn luminance((r, g, b): Rgb) -> f64 {
    let lin = |c: u8| {
        let c = c as f64 / 255.0;
        if c <= 0.03928 {
            c / 12.92
        } else {
            ((c + 0.055) / 1.055).powf(2.4)
        }
    };
    0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)
}

fn contrast(a: Rgb, b: Rgb) -> f64 {
    let (x, y) = (luminance(a), luminance(b));
    let (hi, lo) = if x > y { (x, y) } else { (y, x) };
    (hi + 0.05) / (lo + 0.05)
}

fn mix(a: Rgb, b: Rgb, t: f64) -> Rgb {
    let m = |x: u8, y: u8| (x as f64 + (y as f64 - x as f64) * t).round() as u8;
    (m(a.0, b.0), m(a.1, b.1), m(a.2, b.2))
}

fn css_hex((r, g, b): Rgb) -> String {
    format!("#{r:02x}{g:02x}{b:02x}")
}

/// Move `color` toward `toward` in 5% steps until it meets `min` contrast on every background.
fn ensure(color: Rgb, backgrounds: &[Rgb], min: f64, toward: Rgb) -> Rgb {
    (0..=20)
        .map(|i| mix(color, toward, i as f64 / 20.0))
        .find(|c| backgrounds.iter().all(|bg| contrast(*c, *bg) >= min))
        .unwrap_or(toward)
}

fn color(theme: &Theme, key: &str, fallback: Rgb) -> Result<Rgb, ThemeError> {
    theme
        .vars
        .get(key)
        .map_or(Ok(fallback), |hex| hex_to_rgb(hex))
}

fn colors(theme: &Theme) -> Result<String, ThemeError> {
    let dark = theme
        .vars
        .get("VARIANT")
        .map(String::as_str)
        .unwrap_or("dark")
        == "dark";
    let (black, white) = ((0, 0, 0), (255, 255, 255));
    let toward = if dark { white } else { black };

    let bg = color(theme, "BASE00", (0x20, 0x21, 0x2b))?;
    let surface = color(theme, "BASE01", bg)?;
    let raised = color(theme, "BASE02", surface)?;
    let edge = color(theme, "BORDER_COLOR", color(theme, "BASE03", raised)?)?;
    let fg_raw = color(theme, "BASE05", (0xe4, 0xe6, 0xef))?;
    let muted_raw = color(theme, "BASE04", fg_raw)?;
    let accent_raw = color(theme, "BASE0D", (0x72, 0x99, 0xe6))?;

    let surfaces = [bg, surface, raised];
    let fg = ensure(fg_raw, &surfaces, 7.0, toward);
    let dim = ensure(muted_raw, &surfaces, 4.5, toward);
    let accent = ensure(accent_raw, &[bg], 3.0, toward);
    let on_accent = if contrast(bg, accent) >= contrast(fg, accent) {
        bg
    } else {
        fg
    };
    let deep = if dark { mix(bg, black, 0.4) } else { bg };
    let hover = mix(raised, fg, 0.08);
    let radius = theme
        .vars
        .get("CORNER_RADIUS")
        .and_then(|v| v.parse::<u8>().ok())
        .unwrap_or(10)
        .min(16);

    let uri = palette_uri();
    Ok(format!(
        "/* Generated by theme-manager. Do not edit manually.\n\
         To use: enable toolkit.legacyUserProfileCustomizations.stylesheets in about:config.\n\
         Open about:support > Profile Directory and create chrome/userChrome.css.\n\
         Put this import first in userChrome.css (before any rules):\n\
           @import url(\"{uri}\");\n\
         Palette variables only: use var(--tm-bg), var(--tm-fg), etc. in your own rules.\n\
         Fully restart Firefox after setup and after each theme switch. */\n:root {{\n\
         \x20   --tm-deep: {};\n    --tm-bg: {};\n    --tm-surface: {};\n    --tm-raised: {};\n\
         \x20   --tm-hover: {};\n    --tm-border: {};\n    --tm-fg: {};\n    --tm-dim: {};\n\
         \x20   --tm-accent: {};\n    --tm-on-accent: {};\n    --tm-radius: {radius}px;\n}}\n",
        css_hex(deep),
        css_hex(bg),
        css_hex(surface),
        css_hex(raised),
        css_hex(hover),
        css_hex(edge),
        css_hex(fg),
        css_hex(dim),
        css_hex(accent),
        css_hex(on_accent),
    ))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashMap;

    #[test]
    fn registered_writer_generates_palette_and_setup_instructions() {
        let theme = Theme {
            name: "t".into(),
            path: "/tmp/t".into(),
            vars: HashMap::new(),
        };
        let writers = crate::writers::all_writers(&theme);
        let firefox: Vec<_> = writers
            .iter()
            .filter(|w| w.name() == "firefox-css")
            .collect();
        assert_eq!(firefox.len(), 1);
        assert_eq!(
            firefox[0].output_path(),
            crate::home().join(".config/theme-manager/firefox-colors.css")
        );
        let out = firefox[0].generate(&theme).unwrap();
        assert!(out.contains(&format!("@import url(\"{}\");", palette_uri())));
        assert!(out.contains("toolkit.legacyUserProfileCustomizations.stylesheets"));
        assert!(out.contains("chrome/userChrome.css"));
        assert!(out.contains("Fully restart Firefox"));
        for variable in [
            "deep",
            "bg",
            "surface",
            "raised",
            "hover",
            "border",
            "fg",
            "dim",
            "accent",
            "on-accent",
            "radius",
        ] {
            assert!(out.contains(&format!("--tm-{variable}:")));
        }
    }

    #[test]
    fn light_palette_and_radius_are_supported() {
        let mut theme = Theme {
            name: "light".into(),
            path: "/tmp/t".into(),
            vars: HashMap::new(),
        };
        theme.vars.extend([
            ("VARIANT".into(), "light".into()),
            ("BASE00".into(), "#ffffff".into()),
            ("BASE05".into(), "#eeeeee".into()),
            ("CORNER_RADIUS".into(), "99".into()),
        ]);
        let out = FirefoxCss.generate(&theme).unwrap();
        assert!(out.contains("--tm-deep: #ffffff;"));
        assert!(out.contains("--tm-radius: 16px;"));
        let fg = out
            .split("--tm-fg: ")
            .nth(1)
            .unwrap()
            .split(';')
            .next()
            .unwrap();
        assert!(contrast(hex_to_rgb(fg).unwrap(), (255, 255, 255)) >= 7.0);
    }

    #[test]
    fn low_contrast_palette_gets_readable_text() {
        let mut theme = Theme {
            name: "t".into(),
            path: "/tmp/t".into(),
            vars: HashMap::new(),
        };
        theme.vars.extend([
            ("BASE00".into(), "#131C19".into()),
            ("BASE01".into(), "#1a2622".into()),
            ("BASE02".into(), "#222e2b".into()),
            ("BASE04".into(), "#3c474a".into()),
            ("BASE05".into(), "#444F4C".into()),
        ]);
        let out = colors(&theme).unwrap();
        let fg = out
            .split("--tm-fg: ")
            .nth(1)
            .unwrap()
            .split(';')
            .next()
            .unwrap();
        assert!(contrast(hex_to_rgb(fg).unwrap(), hex_to_rgb("#222e2b").unwrap()) >= 7.0);
        theme.vars.insert("BASE00".into(), "broken".into());
        assert!(colors(&theme).is_err());
    }
}
