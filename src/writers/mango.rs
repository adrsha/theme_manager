use crate::{hex_to_rgb, Theme, ThemeError, Writer};
use std::path::PathBuf;
use std::process::{Command, Stdio};

/// Generated colours for the mango (mangowc) compositor.
///
/// Only colours are generated. Geometry (`border_px`, `border_radius`, gaps)
/// stays in the user's own mango config: theme defaults (BORDER_SIZE=0) would
/// otherwise silently remove borders the user configured there.
///
/// Fallback behaviour: the user keeps hard-coded colours in their own config
/// *above* the `source_optional` line. Mango ignores a missing optional file,
/// and this writer skips any colour it cannot resolve instead of failing, so
/// mango always has a complete, readable palette.
pub struct Mango;

/// (mango option, theme key, fallback theme key, alpha byte as hex)
const COLORS: &[(&str, &str, Option<&str>, &str)] = &[
    ("root_color", "DARKER_BLACK", Some("BASE00"), "ff"),
    ("border_color", "BORDER_COLOR", None, "ff"),
    ("focus_color", "BASE0D", None, "ff"),
    ("urgent_color", "BASE08", None, "ff"),
    ("maximized_screen_color", "BASE0A", None, "ff"),
    ("scratchpad_color", "BASE09", None, "ff"),
    ("global_color", "BASE0E", None, "ff"),
    ("overlay_color", "BASE0B", None, "ff"),
    ("drop_color", "BASE0B", None, "55"),
    ("split_color", "BASE09", None, "ff"),
];

/// "#rrggbb" + alpha byte -> mango's "0xrrggbbaa".
fn mango_color(hex: &str, alpha: &str) -> Result<String, ThemeError> {
    let (r, g, b) = hex_to_rgb(hex)?;
    Ok(format!("0x{r:02x}{g:02x}{b:02x}{alpha}"))
}

impl Writer for Mango {
    fn name(&self) -> &'static str {
        "mango"
    }

    fn output_path(&self) -> PathBuf {
        crate::home().join(".config/mango/theme.conf")
    }

    fn enabled(&self) -> bool {
        crate::app_enabled("mango", ".config/mango")
    }

    fn generate(&self, theme: &Theme) -> Result<String, ThemeError> {
        let mut out = String::from(
            "# Generated by theme-manager -- do not edit manually.\n\
             # To use: add this line to ~/.config/mango/config.conf, AFTER your own\n\
             # colour settings (those stay as the fallback if this file is missing):\n\
             #   source_optional=~/.config/mango/theme.conf\n\
             #\n",
        );

        for (option, key, fallback, alpha) in COLORS {
            let value = theme
                .vars
                .get(*key)
                .or_else(|| fallback.and_then(|f| theme.vars.get(f)));
            let Some(value) = value else {
                eprintln!("theme-manager: [mango] {key} not in theme, keeping mango's own {option}");
                continue;
            };
            match mango_color(value, alpha) {
                Ok(color) => out.push_str(&format!("{option}={color}\n")),
                Err(error) => {
                    eprintln!("theme-manager: [mango] skipping {option}: {error}")
                }
            }
        }
        Ok(out)
    }

    fn reload(&self) {
        // mmsg talks to mango over Wayland, so it needs WAYLAND_DISPLAY. A
        // systemd user service usually does not have it: find the socket.
        let display = std::env::var("WAYLAND_DISPLAY")
            .ok()
            .filter(|d| !d.is_empty())
            .or_else(find_wayland_socket);

        // Current syntax first, then the older `-d` flag form.
        let attempts: [&[&str]; 2] = [&["dispatch", "reload_config"], &["-d", "reload_config"]];
        for args in attempts {
            let mut cmd = Command::new("mmsg");
            cmd.args(args).stdout(Stdio::null()).stderr(Stdio::null());
            if let Some(display) = &display {
                cmd.env("WAYLAND_DISPLAY", display);
            }
            if cmd.status().map(|s| s.success()).unwrap_or(false) {
                return;
            }
        }
        eprintln!("theme-manager: [mango] reload failed (mmsg missing or mango not running)");
    }
}

/// First `wayland-N` socket in $XDG_RUNTIME_DIR.
fn find_wayland_socket() -> Option<String> {
    let dir = std::env::var("XDG_RUNTIME_DIR").ok()?;
    let mut names: Vec<String> = std::fs::read_dir(dir)
        .ok()?
        .flatten()
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| n.starts_with("wayland-") && !n.ends_with(".lock"))
        .collect();
    names.sort();
    names.into_iter().next()
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashMap;

    fn theme(vars: &[(&str, &str)]) -> Theme {
        Theme {
            name: "t".into(),
            path: "/tmp/t".into(),
            vars: HashMap::from_iter(vars.iter().map(|(k, v)| (k.to_string(), v.to_string()))),
        }
    }

    #[test]
    fn emits_mango_colour_format() {
        let t = theme(&[
            ("DARKER_BLACK", "#0a0b0c"),
            ("BORDER_COLOR", "#445566"),
            ("BASE0D", "#8baa9b"),
            ("BASE0B", "#95c381"),
        ]);
        let out = Mango.generate(&t).unwrap();
        assert!(out.contains("root_color=0x0a0b0cff\n"));
        assert!(out.contains("border_color=0x445566ff\n"));
        assert!(out.contains("focus_color=0x8baa9bff\n"));
        assert!(out.contains("overlay_color=0x95c381ff\n"));
        assert!(out.contains("drop_color=0x95c38155\n"));
        assert!(out.contains("source_optional=~/.config/mango/theme.conf"));
    }

    #[test]
    fn skips_missing_or_invalid_colours_instead_of_failing() {
        let t = theme(&[("BASE0D", "#8baa9b"), ("BASE08", "not-a-colour")]);
        let out = Mango.generate(&t).unwrap();
        assert!(out.contains("focus_color=0x8baa9bff\n"));
        // Invalid and absent keys produce no line, so mango keeps its own value.
        assert!(!out.contains("urgent_color"));
        assert!(!out.contains("global_color"));
    }

    #[test]
    fn root_colour_falls_back_to_base00() {
        let t = theme(&[("BASE00", "#101112")]);
        assert!(Mango
            .generate(&t)
            .unwrap()
            .contains("root_color=0x101112ff\n"));
    }

    #[test]
    fn never_generates_geometry() {
        let t = theme(&[("BORDER_SIZE", "0"), ("CORNER_RADIUS", "20")]);
        let out = Mango.generate(&t).unwrap();
        assert!(!out.contains("border_px"));
        assert!(!out.contains("border_radius"));
    }
}
