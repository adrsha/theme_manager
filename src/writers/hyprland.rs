use crate::{Theme, ThemeError, Writer};
use std::path::PathBuf;
use std::process::{Command, Stdio};

pub struct Hyprland;

impl Writer for Hyprland {
    fn name(&self) -> &'static str {
        "hyprland"
    }

    fn output_path(&self) -> PathBuf {
        crate::home().join(".config/hypr/colors.lua")
    }

    fn enabled(&self) -> bool {
        crate::app_enabled("hyprctl", ".config/hypr")
    }

    fn generate(&self, theme: &Theme) -> Result<String, ThemeError> {
        let border = theme.require("BORDER_COLOR")?.trim_start_matches('#');
        let border_size = theme.require("BORDER_SIZE")?;
        let corner_radius = theme.require("CORNER_RADIUS")?;
        let bg = theme.require("DARKER_BLACK")?.trim_start_matches('#');

        Ok(format!(
            "-- Generated by theme-manager -- do not edit manually.\n\
             -- To use: add this line to ~/.config/hypr/hyprland.lua:\n\
             --   require(\"colors\")\n\
             --\n\
             hl.config({{\n\
             \tgeneral = {{\n\
             \t\tborder_size = {border_size},\n\
             \t\tcol = {{\n\
             \t\t\tactive_border = \"rgb({border})\",\n\
             \t\t\tinactive_border = \"rgb({border})\",\n\
             \t\t}},\n\
             \t}},\n\
             \tdecoration = {{\n\
             \t\trounding = {corner_radius},\n\
             \t}},\n\
             \tmisc = {{\n\
             \t\tbackground_color = \"rgb({bg})\",\n\
             \t}},\n\
             }})\n"
        ))
    }

    fn reload(&self) {
        let _ = Command::new("hyprctl")
            .args(["reload", "config-only"])
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status();
    }
}
